"""Generate adversarial holdout cases whose labels come from a transformation.

The hand-labelled corpora were written by the same people who tuned the rules,
so a perfect score on them can be a tautology. The cases generated here are
labelled by what the generator did, never by running a rule:

- SIMILAR-001 / DRY-001 (``duplication_similar``): each seed function in
  ``seeds/cpython_seeds.py`` (verbatim CPython code) is paired with an edited
  copy. A label-preserving edit (rename identifiers, reorder independent
  statements) leaves a duplicate, flag true; a label-breaking edit (flip an
  operator, add a branch, change a called name) leaves two different
  functions, flag false. Changing the string literals keeps an exact clone
  for DRY-001, which abstracts strings, and breaks a near-duplicate for
  SIMILAR-001, which requires them to agree, so that case carries one flag
  per rule.
- CMT-001 (``comments_commented_code``): real one-line statements from the
  corpus's own code, commented out, are commented-out code (flag true);
  sentences from the corpus's own docstrings, as comments, are prose (flag
  false).

Everything lands in ``holdout/generated/`` with ``source:
generated:<transform>``, and every random choice is seeded, so a rerun writes
the same bytes. The run replaces the previous generated files and their labels.

Usage:
    uv run python evals/generate_adversarial.py           # write the cases
    uv run python evals/generate_adversarial.py --check   # exit 1 if stale

Exit codes: 0 written, or up to date under ``--check``; 1 stale under ``--check``.
"""

from __future__ import annotations

import argparse
import ast
import random
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from code_transforms import PER_RULE, PRESERVING, TRANSFORMS, apply_transform, strip_docstring
from labelled_corpus import (
    CORPORA_ROOT,
    GENERATED_PREFIX,
    FileEntry,
    LabelsDocument,
    SiteLabel,
    hash_line,
    read_labels,
    render_labels,
)

SEED = 20260925
DUPLICATION_CORPUS = "duplication_similar"
COMMENT_CORPUS = "comments_commented_code"
COMMENTS_PER_FILE = 12
FILES_PER_COMMENT_TRANSFORM = 2
GENERATOR = "evals/generate_adversarial.py"
_SIMPLE_STATEMENTS = (
    ast.Assign, ast.AugAssign, ast.AnnAssign, ast.Return, ast.Import, ast.ImportFrom,
    ast.Raise, ast.Assert, ast.Delete,
)  # fmt: skip
_CODE_CHARACTERS = re.compile(r"[`=()\[\]{}<>_#\\:;\"']")
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+")
_MAX_COMMENT = 72


@dataclass(frozen=True)
class GeneratedCase:
    """One generated file: its text and the label entry that describes it."""

    text: str
    entry: FileEntry


def build_duplication_cases() -> dict[str, GeneratedCase]:
    """Pair every seed with each transform's edit of it, keyed by corpus path."""
    seeds_path = CORPORA_ROOT / DUPLICATION_CORPUS / "seeds" / "cpython_seeds.py"
    tree = ast.parse(seeds_path.read_text(encoding="utf-8"))
    origins = read_seed_origins(tree=tree)
    cases: dict[str, GeneratedCase] = {}
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef):
            continue
        seed = strip_docstring(function=node)
        for transform in TRANSFORMS:
            rng = random.Random(f"{SEED}:{DUPLICATION_CORPUS}:{seed.name}:{transform}")
            variant = apply_transform(function=seed, transform=transform, rng=rng)
            if variant is None:
                continue
            path = f"{GENERATED_PREFIX}gen_{transform}_{seed.name.lstrip('_')}.py"
            cases[path] = build_duplication_case(
                seed=seed,
                variant=variant,
                transform=transform,
                origin=f"{origins[node.name]}:{node.name}",
            )
    return cases


def read_seed_origins(*, tree: ast.Module) -> dict[str, str]:
    """Return the ``SEED_ORIGINS`` mapping declared in the seeds module."""
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "SEED_ORIGINS" for target in node.targets
        ):
            return ast.literal_eval(node.value)
    raise ValueError("the seeds module declares no SEED_ORIGINS")


def build_duplication_case(
    *,
    seed: ast.FunctionDef,
    variant: ast.FunctionDef,
    transform: str,
    origin: str,
) -> GeneratedCase:
    """Render a seed and its variant as one file, labelled by the transform."""
    flag, kind, verdict = describe_transform(transform=transform)
    header = (
        f'"""Generated by {GENERATOR}; do not edit by hand.\n\n'
        f"Seed {seed.name} ({origin}); transform {transform} ({kind}),\n"
        f'so the two functions are {verdict}.\n"""\n'
    )
    text = header + "\n\n" + ast.unparse(seed) + "\n\n\n" + ast.unparse(variant) + "\n"
    entry: FileEntry = {
        "split": "holdout",
        "source": f"generated:{transform}",
        "labelled_by": GENERATOR,
        "labelled_before_rule": True,
        "seed": origin,
        "flag": flag,
        "note": f"{kind} transform {transform}: {verdict}",
    }
    return GeneratedCase(text=text, entry=entry)


def describe_transform(*, transform: str) -> tuple[bool | dict[str, bool], str, str]:
    """Return a transform's label, its kind and the verdict it implies."""
    if transform in PRESERVING:
        return True, "label-preserving", "still duplicates"
    if transform in PER_RULE:
        flags = PER_RULE[transform]
        holds = ", ".join(rule for rule, flag in sorted(flags.items()) if flag)
        breaks = ", ".join(rule for rule, flag in sorted(flags.items()) if not flag)
        return (
            flags,
            f"label-preserving for {holds}, label-breaking for {breaks}",
            f"still duplicates to {holds} and no longer duplicates to {breaks}",
        )
    return False, "label-breaking", "no longer duplicates"


def list_hand_labelled(*, corpus: Path) -> list[Path]:
    """Return the corpus files that were not generated, in path order."""
    document = read_labels(corpus=corpus)
    return [
        corpus / path
        for path, entry in sorted(document["files"].items())
        if not entry["source"].startswith("generated:")
    ]


def collect_statements(*, corpus: Path) -> list[tuple[str, str]]:
    """Return ``(text, origin)`` for each distinct one-line simple statement."""
    found: dict[str, str] = {}
    for path in list_hand_labelled(corpus=corpus):
        source = path.read_text(encoding="utf-8")
        for node in ast.walk(ast.parse(source)):
            text = read_commentable_text(node=node, source=source)
            if text:
                found.setdefault(text, f"{path.relative_to(corpus).as_posix()}:{node.lineno}")
    return sorted(found.items())


def read_commentable_text(*, node: ast.AST, source: str) -> str | None:
    """Return a simple statement's one-line source, or None if it does not qualify."""
    if not isinstance(node, _SIMPLE_STATEMENTS) and not is_call_statement(node=node):
        return None
    text = ast.get_source_segment(source, node) or ""
    if not text or "\n" in text or len(text) > _MAX_COMMENT or text == "return":
        return None
    return text


def is_call_statement(*, node: ast.AST) -> bool:
    """True for an expression statement that is a call."""
    return isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)


def collect_sentences(*, corpus: Path) -> list[tuple[str, str]]:
    """Return ``(sentence, origin)`` for each prose sentence of a docstring."""
    found: dict[str, str] = {}
    kinds = (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
    for path in list_hand_labelled(corpus=corpus):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            docstring = ast.get_docstring(node) if isinstance(node, kinds) else None
            for sentence in _SENTENCE_END.split(" ".join((docstring or "").split())):
                if is_prose(sentence=sentence):
                    found.setdefault(sentence, path.relative_to(corpus).as_posix())
    return sorted(found.items())


def is_prose(*, sentence: str) -> bool:
    """True for a plain sentence: capitalised, 4 to 14 words, no code characters."""
    words = sentence.split()
    return (
        4 <= len(words) <= 14
        and len(sentence) <= _MAX_COMMENT
        and sentence[0].isupper()
        and sentence.endswith(".")
        and not _CODE_CHARACTERS.search(sentence)
    )


def build_comment_cases() -> dict[str, GeneratedCase]:
    """Write commented statements and docstring prose into generated files."""
    corpus = CORPORA_ROOT / COMMENT_CORPUS
    pools = {
        "comment_statement": (collect_statements(corpus=corpus), True),
        "docstring_sentence": (collect_sentences(corpus=corpus), False),
    }
    cases: dict[str, GeneratedCase] = {}
    for transform, (pool, flag) in pools.items():
        rng = random.Random(f"{SEED}:{COMMENT_CORPUS}:{transform}")
        wanted = COMMENTS_PER_FILE * FILES_PER_COMMENT_TRANSFORM
        chosen = rng.sample(pool, min(wanted, len(pool)))
        for number in range(FILES_PER_COMMENT_TRANSFORM):
            batch = chosen[number * COMMENTS_PER_FILE : (number + 1) * COMMENTS_PER_FILE]
            if batch:
                path = f"{GENERATED_PREFIX}gen_{transform}_{number + 1:02d}.py"
                cases[path] = build_comment_case(transform=transform, batch=batch, flag=flag)
    return cases


def build_comment_case(
    *,
    transform: str,
    batch: list[tuple[str, str]],
    flag: bool,
) -> GeneratedCase:
    """Render one function whose comments are the batch, one per code line."""
    verdict = "commented-out code" if flag else "prose, not code"
    lines = [
        f'"""Generated by {GENERATOR}; do not edit by hand.',
        "",
        f"Transform {transform}: every comment below is {verdict}.",
        '"""',
        "",
        "",
        "def generated_case():",
        "    step = 0",
    ]
    labels: list[SiteLabel] = []
    for text, origin in batch:
        lines.append(f"    # {text}")
        labels.append(
            {
                "line": len(lines),
                "flag": flag,
                "note": f"{transform} from {origin}",
                "line_hash": hash_line(text=lines[-1]),
            },
        )
        lines.append("    step += 1")
    lines.append("    return step")
    entry: FileEntry = {
        "split": "holdout",
        "source": f"generated:{transform}",
        "labelled_by": GENERATOR,
        "labelled_before_rule": True,
        "labels": labels,
    }
    return GeneratedCase(text="\n".join(lines) + "\n", entry=entry)


def merge_labels(*, document: LabelsDocument, cases: dict[str, GeneratedCase]) -> LabelsDocument:
    """Replace the generated entries of a labels document with *cases*."""
    files = {
        path: entry
        for path, entry in document["files"].items()
        if not path.startswith(GENERATED_PREFIX)
    }
    files.update({path: case.entry for path, case in cases.items()})
    return {**document, "files": files}


def find_stale(*, corpus: Path, cases: dict[str, GeneratedCase]) -> list[str]:
    """Return what differs between the corpus on disk and the generated cases."""
    stale: list[str] = []
    on_disk = {
        path.relative_to(corpus).as_posix()
        for path in (corpus / GENERATED_PREFIX).glob("*")
        if path.is_file()
    }
    stale.extend(f"{corpus.name}/{path}: not generated" for path in sorted(on_disk - set(cases)))
    for path, case in sorted(cases.items()):
        target = corpus / path
        if not target.is_file() or target.read_text(encoding="utf-8") != case.text:
            stale.append(f"{corpus.name}/{path}: differs from a fresh generation")
    merged = merge_labels(document=read_labels(corpus=corpus), cases=cases)
    if (corpus / "labels.json").read_text(encoding="utf-8") != render_labels(document=merged):
        stale.append(f"{corpus.name}/labels.json: generated labels differ")
    return stale


def write_cases(*, corpus: Path, cases: dict[str, GeneratedCase]) -> None:
    """Replace the corpus' generated files and their labels with *cases*."""
    generated = corpus / GENERATED_PREFIX
    generated.mkdir(parents=True, exist_ok=True)
    for path in generated.glob("*"):
        if path.is_file():
            path.unlink()
    for path, case in cases.items():
        (corpus / path).write_text(case.text, encoding="utf-8")
    merged = merge_labels(document=read_labels(corpus=corpus), cases=cases)
    (corpus / "labels.json").write_text(render_labels(document=merged), encoding="utf-8")


def build_all_cases() -> dict[str, dict[str, GeneratedCase]]:
    """Return the generated cases of every corpus the generator covers."""
    return {
        DUPLICATION_CORPUS: build_duplication_cases(),
        COMMENT_CORPUS: build_comment_cases(),
    }


def main(*, argv: list[str]) -> int:
    """Write the generated cases, or with ``--check`` report whether they are stale."""
    parser = argparse.ArgumentParser(prog="generate_adversarial.py", description=__doc__)
    parser.add_argument("--check", action="store_true", help="Exit 1 if the files are stale.")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for name, cases in build_all_cases().items():
        corpus = CORPORA_ROOT / name
        if args.check:
            stale.extend(find_stale(corpus=corpus, cases=cases))
        else:
            write_cases(corpus=corpus, cases=cases)
            print(f"{name}: wrote {len(cases)} generated file(s)")
    for line in stale:
        print(line)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main(argv=sys.argv[1:]))
